import { test, expect, login } from "./fixtures";

test("creation stages preserve work, require renewed image confirmation, and keep publishing explicit", async ({ page, accounts }, testInfo) => {
  const owner = await accounts.create();
  await login(page, owner);
  await page.goto("/challenges/new");
  await expect(page.getByLabel("Your caption")).toBeHidden();
  await expect(page.getByRole("button", { name: "Continue to caption" })).toBeDisabled();
  await expect(page.getByText(/Google’s free API tier/)).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("image-desktop.png"), fullPage: true });
  await page.getByLabel("Image source").selectOption("template");
  const option = await page.getByLabel("Gallery template").locator("option:not([disabled])").first().getAttribute("value");
  await page.getByLabel("Gallery template").selectOption(option!);
  await page.getByText("Review image understanding", { exact: true }).click();
  await page.getByLabel("I confirm this image description").check();
  await page.getByRole("button", { name: "Continue to caption" }).click();
  await expect(page.getByRole("heading", { name: "Write your contender" })).toBeFocused();
  await expect(page.getByLabel("Image source")).toBeHidden();
  await page.getByLabel("Your caption").fill("My schedule has filed a restraining order against free time.");
  await page.getByLabel("Add context for the joke (optional)").fill("Finals week");
  await page.getByRole("button", { name: "Back to image" }).click();
  await expect(page.getByRole("heading", { name: "Choose and review your image" })).toBeFocused();
  await page.getByLabel("Image description", { exact: true }).fill("A surprised cartoon face.");
  await expect(page.getByRole("button", { name: "Continue to caption" })).toBeDisabled();
  await page.getByRole("button", { name: "2. Your caption" }).click();
  await expect(page.getByLabel("Your caption")).toHaveValue("My schedule has filed a restraining order against free time.");
  await expect(page.getByRole("button", { name: "Create draft", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "Back to image" }).click();
  await page.getByLabel("I confirm this image description").check();
  await page.getByRole("button", { name: "Continue to caption" }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByLabel("Add context for the joke (optional)")).toHaveValue("Finals week");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("caption-mobile.png"), fullPage: true });
  await page.getByRole("button", { name: "Create draft", exact: true }).click();
  await expect(page).toHaveURL(/\/challenges\/[0-9a-f-]+$/);
  await expect(page.getByRole("heading", { name: "Review your matchup" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Generate AI opponent" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Publish for 24 hours" })).toHaveCount(0);
  const { data: draft } = await owner.client.from("challenges").select("status,published_at").single();
  expect(draft).toMatchObject({ status: "draft", published_at: null });
  expect((await owner.client.from("challenge_generations").select("id")).data).toEqual([]);
});
