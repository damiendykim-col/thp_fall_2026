  const voter = await accounts.create();
  const moderator = await accounts.create();
  const path = `${owner.id}/moderation.jpg`;
  const bytes = await sharp({ create: { width: 8, height: 8, channels: 3, background: "yellow" } }).jpeg().toBuffer();
