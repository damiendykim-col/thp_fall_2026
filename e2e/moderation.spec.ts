  await approveForTest(accounts.admin, owner.id, id);
  expect((await owner.client.rpc("publish_caption_challenge", { p_challenge: id })).error).toBeNull();
  const { data: challenge } = await voter.client.rpc("read_caption_challenge", { p_challenge: id });
  expect((await voter.client.rpc("vote_caption_challenge", { p_challenge: id, p_caption: challenge.captions[0].id })).error).toBeNull();
