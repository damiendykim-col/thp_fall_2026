test("moderators can dismiss reports and creators can withdraw their own published challenge", async ({ page, accounts }) => {
  const owner = await accounts.create();
  const reporter = await accounts.create();
  const moderator = await accounts.create();
  const { data: images } = await accounts.admin.from("images").select("id,image_url").limit(1);
  const { data: challenge, error } = await accounts.admin.from("challenges").insert({ creator_id: owner.id, template_id: images![0].id, template_url: images![0].image_url, situation: "Owner withdrawal fixture", status: "published", closes_at: new Date(Date.now() + 86400000).toISOString() }).select("id").single();
  expect(error).toBeNull();
  const id = challenge!.id;
  expect((await reporter.client.rpc("report_challenge", { p_challenge: id, p_reason: "other" })).error).toBeNull();
  const { data: report } = await reporter.client.from("challenge_reports").select("id").single();
  expect((await reporter.client.rpc("dismiss_challenge_report", { p_report: report!.id })).error).toBeTruthy();
  expect((await accounts.admin.from("moderators").insert({ user_id: moderator.id })).error).toBeNull();
  await login(page, moderator);
  await page.goto("/moderation");
  await page.getByRole("button", { name: "Dismiss report" }).click();
  await expect(page.getByText("No open reports.")).toBeVisible();
  expect((await reporter.client.rpc("read_caption_challenge", { p_challenge: id })).data).not.toBeNull();
  await page.getByText("Account", { exact: true }).click();
  await page.getByRole("button", { name: "Sign out" }).click();
  await expect(page).toHaveURL(/\/login$/);
  await login(page, owner);
  await page.goto(`/challenges/${id}`);
  await page.getByText("Manage visibility", { exact: true }).click();
  await page.getByRole("button", { name: "Hide challenge", exact: true }).click();
  await expect(page.getByText("This challenge is hidden from other members. Voting and publication are disabled.")).toBeVisible();
  expect((await reporter.client.rpc("read_caption_challenge", { p_challenge: id })).data).toBeNull();
});

test("moderation claims are exclusive, cached, bounded and count old retries against today's quota", async ({ accounts }) => {
  const owner = await accounts.create();
  const args = { p_owner: owner.id, p_phase: "human", p_hash: "exclusive", p_policy: "moderation-v1", p_provider: "mock", p_model: "fixture" };
  expect((await owner.client.rpc("claim_moderation", args)).error).toBeTruthy();
  const claims = await Promise.all([accounts.admin.rpc("claim_moderation", args), accounts.admin.rpc("claim_moderation", args)]);
  expect(claims.filter(c => c.data?.claimed)).toHaveLength(1);
  const claimed = claims.find(c => c.data?.claimed)!.data;
  expect((await accounts.admin.from("moderation_checks").update({ status: "approved" }).eq("id", claimed.id)).error).toBeNull();
  const cached = await accounts.admin.rpc("claim_moderation", args);
  expect(cached.data).toMatchObject({ id: claimed.id, status: "approved", attempts: 1, claimed: false });
  const { data: old } = await accounts.admin.from("moderation_checks").insert({ owner_id: owner.id, phase: "human", input_hash: "old", policy_version: "moderation-v1", provider: "mock", model: "fixture", status: "error", attempts: 2, created_at: "2000-01-01T00:00:00Z", started_at: "2000-01-01T00:00:00Z" }).select("id").single();
  const retry = await accounts.admin.rpc("claim_moderation", { ...args, p_hash: "old" });
  expect(retry.error).toBeNull();
  expect(retry.data.attempts).toBe(3);
  expect((await accounts.admin.from("moderation_checks").update({ status: "error" }).eq("id", old!.id)).error).toBeNull();
  expect((await accounts.admin.rpc("claim_moderation", { ...args, p_hash: "old" })).error).toBeTruthy();
  const remaining = await Promise.all(Array.from({ length: 40 }, (_, i) => accounts.admin.rpc("claim_moderation", { ...args, p_hash: `quota-${i}` })));
  expect(remaining.filter(r => !r.error)).toHaveLength(36);
});
